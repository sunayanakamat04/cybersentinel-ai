"""SQLAlchemy ORM models for CyberSentinel AI."""

import uuid
from datetime import datetime, timezone
from typing import List, Optional
from sqlalchemy import (
    Boolean,
    Column,
    DateTime,
    Float,
    ForeignKey,
    Integer,
    String,
    Text,
)
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.types import JSON
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column, relationship


class Base(DeclarativeBase):
    pass


class FlowRecord(Base):
    """Network flow record entry."""

    __tablename__ = "flow_records"

    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=lambda: str(uuid.uuid4()))
    flow_id: Mapped[Optional[str]] = mapped_column(String(100), index=True)
    timestamp: Mapped[datetime] = mapped_column(DateTime, default=lambda: datetime.now(timezone.utc))
    src_ip: Mapped[str] = mapped_column(String(45), default="0.0.0.0")
    src_port: Mapped[int] = mapped_column(Integer, default=0)
    dst_ip: Mapped[str] = mapped_column(String(45), default="0.0.0.0")
    dst_port: Mapped[int] = mapped_column(Integer, default=0)
    protocol: Mapped[int] = mapped_column(Integer, default=6)
    flow_duration: Mapped[float] = mapped_column(Float, default=0.0)
    total_fwd_packets: Mapped[int] = mapped_column(Integer, default=0)
    total_bwd_packets: Mapped[int] = mapped_column(Integer, default=0)
    flow_bytes_per_sec: Mapped[float] = mapped_column(Float, default=0.0)
    flow_packets_per_sec: Mapped[float] = mapped_column(Float, default=0.0)
    raw_features: Mapped[Optional[dict]] = mapped_column(JSON, default=dict)
    created_at: Mapped[datetime] = mapped_column(DateTime, default=lambda: datetime.now(timezone.utc))

    # Relationships
    alert: Mapped[Optional["Alert"]] = relationship("Alert", back_populates="flow_record", uselist=False)


class Alert(Base):
    """Prioritized security alert generated by hybrid inference engine."""

    __tablename__ = "alerts"

    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=lambda: str(uuid.uuid4()))
    flow_record_id: Mapped[Optional[str]] = mapped_column(String(36), ForeignKey("flow_records.id"), nullable=True)
    priority: Mapped[str] = mapped_column(String(20), index=True)  # CRITICAL, HIGH, MEDIUM, LOW, INFO
    attack_class: Mapped[str] = mapped_column(String(50), index=True)
    supervised_confidence: Mapped[float] = mapped_column(Float, default=0.0)
    anomaly_score: Mapped[float] = mapped_column(Float, default=0.0)
    is_anomaly: Mapped[bool] = mapped_column(Boolean, default=False)
    rule_matched: Mapped[str] = mapped_column(String(100), default="DEFAULT")
    status: Mapped[str] = mapped_column(String(30), default="OPEN")  # OPEN, UNDER_INVESTIGATION, CONFIRMED, RESOLVED
    assigned_analyst: Mapped[Optional[str]] = mapped_column(String(100), nullable=True)
    triage_notes: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    created_at: Mapped[datetime] = mapped_column(DateTime, default=lambda: datetime.now(timezone.utc), index=True)
    updated_at: Mapped[datetime] = mapped_column(DateTime, default=lambda: datetime.now(timezone.utc), onupdate=lambda: datetime.now(timezone.utc))

    # Relationships
    flow_record: Mapped[Optional[FlowRecord]] = relationship("FlowRecord", back_populates="alert")
    explanations: Mapped[List["ExplanationFeature"]] = relationship("ExplanationFeature", back_populates="alert", cascade="all, delete-orphan")


class ExplanationFeature(Base):
    """Local SHAP feature attribution element for an alert."""

    __tablename__ = "explanation_features"

    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=lambda: str(uuid.uuid4()))
    alert_id: Mapped[str] = mapped_column(String(36), ForeignKey("alerts.id"), index=True)
    feature_name: Mapped[str] = mapped_column(String(100))
    feature_value: Mapped[float] = mapped_column(Float, default=0.0)
    shap_attribution: Mapped[float] = mapped_column(Float, default=0.0)
    rank: Mapped[int] = mapped_column(Integer, default=1)
    impact_description: Mapped[Optional[str]] = mapped_column(String(255), nullable=True)

    # Relationships
    alert: Mapped[Alert] = relationship("Alert", back_populates="explanations")


class DriftSnapshot(Base):
    """Historical traffic drift evaluation log."""

    __tablename__ = "drift_snapshots"

    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=lambda: str(uuid.uuid4()))
    evaluated_at: Mapped[datetime] = mapped_column(DateTime, default=lambda: datetime.now(timezone.utc), index=True)
    feature_name: Mapped[str] = mapped_column(String(100))
    ks_statistic: Mapped[float] = mapped_column(Float, default=0.0)
    ks_p_value: Mapped[float] = mapped_column(Float, default=1.0)
    psi_value: Mapped[float] = mapped_column(Float, default=0.0)
    drift_flagged: Mapped[bool] = mapped_column(Boolean, default=False)
